def build_cache(db: Path = HERE / 'rsr_index.db', log=print) -> dict:
    """{group: {"forgeable": [templates], "per_file": n, "bare": n}} from every
    sfv the RSR store carries. Written to sfv_templates.json."""
    con = sqlite3.connect(f'file:{db}?mode=ro', uri=True)
    out = {}
    seen = set()
    n = 0
    for name, path in con.execute('SELECT name, rsr_path FROM releases'):
        try:
            z = zipfile.ZipFile(path)
            man = json.loads(z.read('manifest.json'))
        except Exception:
            continue
        g = _group(name)
        for f in man.get('sidecars', []):
            if not f['name'].lower().endswith('.sfv') or not f.get('stored'):
                continue
            try:
                t = _detect(z.read(f['stored']))
            except Exception:
                continue
            n += 1
            slot = out.setdefault(g, {'forgeable': [], 'per_file': 0, 'bare': 0})
            if t is None:
                continue
            if t['per_file']:
                slot['per_file'] += 1
                continue
            if not any(isinstance(h, list) for h in t['head']) and not t['head'] and not t['tail']:
                slot['bare'] += 1
            key = json.dumps([g, t], sort_keys=True)
            if key in seen:
                continue
            seen.add(key)
            t['example'] = name
            slot['forgeable'].append(t)
    # The srrdb extras store: every sfv in the folders indexed there (a
    # release-folder pack such as dats.site's extras), its group read from
    # the release folder it sits in.
    xdb = HERE / 'srrdb_extras.db'
    if xdb.is_file():
        xcon = sqlite3.connect(f'file:{xdb}?mode=ro', uri=True)
        for (path,) in xcon.execute("SELECT path FROM files WHERE lower(name) LIKE '%.sfv'"):
            p = Path(path)
            try:
                t = _detect(p.read_bytes())
            except Exception:
                continue
            n += 1
            g = _group(p.parent.name)
            slot = out.setdefault(g, {'forgeable': [], 'per_file': 0, 'bare': 0})
            if t is None:
                continue
            if t['per_file']:
                slot['per_file'] += 1
                continue
            key = json.dumps([g, t], sort_keys=True)
            if key in seen:
                continue
            seen.add(key)
            t['example'] = p.parent.name
            slot['forgeable'].append(t)
    # Tool templates: a header seen in three or more groups is the TOOL's
    # text, not a group's habit (pdSFV's "; Visit http://pdsfv.isonews.com"),
    # so it is worth trying for a group that never used it in the store.
    shape = {}
    for g, slot in out.items():
        if g == '*':
            continue
        for t in slot['forgeable']:
            k = json.dumps([t['head'], t['tail'], t['eol'], t['final']], sort_keys=True)
            shape.setdefault(k, [set(), t])[0].add(g)
    out['*'] = {'forgeable': [t for gs, t in shape.values() if len(gs) >= 3
                              and (t['head'] or t['tail'])],
                'per_file': 0, 'bare': 0}
    CACHE.write_text(json.dumps(out), encoding='utf-8')
    log(f'sfv templates: {n:,} sfvs read, {sum(len(v["forgeable"]) for v in out.values()):,} '
        f'distinct forgeable templates over {len(out):,} groups -> {CACHE.name}')
    return out


def load_cache() -> dict:
    try:
        return json.loads(CACHE.read_text(encoding='utf-8'))
    except (OSError, ValueError):
        return {}


