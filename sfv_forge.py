"""
sfv_forge — rebuild a release's .sfv byte for byte when no copy survives.

An .sfv is the archive names and CRC32s the DAT already lists, plus whatever
its tool wrote around them. 73% of the 27,566 sfvs in the RSR store are bare
entries, which sidecar_fixer.sfv_variants already rebuilds. Most of the rest
carry a fixed header with ONE moment in it ("; Generated by pdSFV v1.2 (WIN)
on 2000-06-29 at 00:41.28"), or a site's or group's fixed stamp
(";SUNSHiNE", "; sfv raped by zipscript-c on the mighty ,dS'").

A group packs with the same tool every time, so its other sfvs in the store
say which header it writes, which case the CRCs are in, the entry order and
the line endings. The header's moment is the one unknown, and the DAT's
release date bounds it: every second of the days around it is tried, the
CRC of the fixed prefix computed once, so a template costs about a second.
Only a candidate matching the DAT's size, CRC32 and MD5/SHA1 is returned.

Not forgeable: tools that list every volume's size and modification time
(WIN-SFV32, QuickSFV, hkSFV, Easy SFV Creator), because those times are not
recorded anywhere a rebuild can read them (the release folders do not keep
them), and QuickPAR ";Q2-" trailers, which carry a hash of their own.
"""

import calendar
import datetime
import hashlib
import json
import re
import sqlite3
import zipfile
import zlib
from pathlib import Path, PurePosixPath

HERE = Path(__file__).parent
CACHE = HERE / 'sfv_templates.json'

_DATE_PREFIX = re.compile(r'^(?:\[[^\]]{1,24}\]\s*)*(\d{4})[-.]?(\d\d)[-.]?(\d\d)[-_.]')
_ENTRY = re.compile(r'^(\S.*?)\s+([0-9A-Fa-f]{8})\s*$')
# a per-volume listing line: "; 20000000  12:30.59 2005-08-31 name"
_PER_FILE = re.compile(r'^;\s*/?-*\s*$|^;\s+[\d.,]+\s+\d{1,2}:\d\d[.:]\d\d')
_MONTHS = {
    'en': ['January', 'February', 'March', 'April', 'May', 'June', 'July',
           'August', 'September', 'October', 'November', 'December'],
    'de': ['Januar', 'Februar', 'März', 'April', 'Mai', 'Juni', 'Juli',
           'August', 'September', 'Oktober', 'November', 'Dezember'],
}

# Date/time fields seen in sfv headers, each with the formatter(s) that write
# it. Ambiguous day/month orders get one formatter each.
def _fmt_iso(sep):
    return lambda d: f'{d:%Y-%m-%d} at {d:%H:%M}{sep}{d:%S}'

def _fmt_slash(dm):
    return (lambda d: f'{d:%d/%m/%Y} at {d:%H:%M:%S}') if dm else \
        (lambda d: f'{d:%m/%d/%Y} at {d:%H:%M:%S}')

def _fmt_slash_ampm(dm):
    def f(d):
        h = d.hour % 12 or 12
        a, b = (d.day, d.month) if dm else (d.month, d.day)
        return f'{a}/{b:02d}/{d.year} at {h}:{d:%M:%S} {"AM" if d.hour < 12 else "PM"}'
    return f

def _fmt_dots():
    return lambda d: f'{d:%m.%d.%Y} at {d:%H:%M:%S}'

def _fmt_words(lang):
    def f(d):
        h = d.hour % 12 or 12
        return (f'{d.day} {_MONTHS[lang][d.month - 1]} {d.year} at '
                f'{h}:{d:%M:%S} {"AM" if d.hour < 12 else "PM"}')
    return f

_FIELDS = [
    (re.compile(r'\d{4}-\d\d-\d\d at \d\d:\d\d\.\d\d'), [_fmt_iso('.')]),
    (re.compile(r'\d{4}-\d\d-\d\d at \d\d:\d\d:\d\d'), [_fmt_iso(':')]),
    (re.compile(r'\d{1,2}/\d\d/\d{4} at \d{1,2}:\d\d:\d\d [AP]M'),
     [_fmt_slash_ampm(False), _fmt_slash_ampm(True)]),
    (re.compile(r'\d\d/\d\d/\d{4} at \d\d:\d\d:\d\d'), [_fmt_slash(False), _fmt_slash(True)]),
    (re.compile(r'\d\d\.\d\d\.\d{4} at \d\d:\d\d:\d\d'), [_fmt_dots()]),
    (re.compile(r'\d{1,2} [A-Za-zä]+ \d{4} at \d{1,2}:\d\d:\d\d [AP]M'),
     [_fmt_words('en'), _fmt_words('de')]),
]


def _detect(data: bytes):
    """The template a sample sfv implies, or None if it is not forgeable."""
    text = data.decode('latin-1')
    eol = '\r\n' if '\r\n' in text else '\n'
    final = text.endswith(eol)
    lines = text.split(eol)
    if final:
        lines = lines[:-1]
    head, entries, tail = [], [], []
    for ln in lines:
        m = _ENTRY.match(ln)
        if m and not ln.startswith(';'):
            if tail:                       # entries after comments after entries
                return None
            entries.append((m.group(1), m.group(2)))
        elif entries:
            tail.append(ln)
        else:
            head.append(ln)
    if not entries:
        return None
    if any(_PER_FILE.match(ln) and re.search(r'\d{1,2}:\d\d', ln) for ln in head + tail):
        return {'per_file': True}
    if any(ln.startswith(';Q2-') for ln in tail):
        return {'per_file': True}           # QuickPAR hash trailer: unforgeable
    # one date/time field at most, in the header
    fields, out_head = [], []
    for ln in head:
        for rx, fmts in _FIELDS:
            m = rx.search(ln)
            if m:
                fields.append(len(out_head))
                out_head.append([ln[:m.start()], fmts, ln[m.end():]])
                break
        else:
            out_head.append(ln)
    if len(fields) > 1:
        return None
    hexes = ''.join(c for _, c in entries)
    upper = any(ch in 'ABCDEF' for ch in hexes) or not any(ch in 'abcdef' for ch in hexes)
    names = [n for n, _ in entries]
    lower = [n.lower() for n in names]
    if lower == sorted(lower):
        order = 'alpha'
    elif lower == sorted(lower, reverse=True):
        order = 'ralpha'
    elif names == sorted(names, key=_vol_key):
        order = 'vol'
    else:
        order = 'other'
    return {'per_file': False, 'eol': eol, 'final': final, 'upper': upper,
            'order': order, 'head': [h if isinstance(h, str) else
                                     [h[0], len(h[1]), h[2]] for h in out_head],
            'field': fields[0] if fields else None,
            'kinds': [rx.pattern for rx, f in _FIELDS
                      for h in out_head if not isinstance(h, str) and h[1] is f],
            'tail': tail}


def _vol_key(name: str):
    n = name.lower()
    m = re.search(r'\.part(\d+)\.rar$', n)
    if m:
        return (0, int(m.group(1)), n)
    if n.endswith('.rar'):
        return (0, -1, n)
    m = re.search(r'\.([r-z])(\d\d)$', n)
    if m:
        return (1, (ord(m.group(1)) - ord('r')) * 100 + int(m.group(2)), n)
    m = re.search(r'\.(\d{3})$', n)
    if m:
        return (1, int(m.group(1)), n)
    return (2, 0, n)


def _group(release: str) -> str:
    s = _DATE_PREFIX.sub('', release)
    return s.rsplit('-', 1)[-1].lower() if '-' in s else ''


